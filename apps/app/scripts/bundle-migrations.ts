// Writes drizzle/*.sql into src/server/db/migrations.gen.ts so the app, the
// CLI and tests all apply the same migrations without a drizzle/ folder at
// runtime. Run after adding or editing a hand-written migration (AGENTS.md).
import fs from "node:fs"
import path from "node:path"

const root = path.resolve(import.meta.dirname, "..")
const dir = path.join(root, "drizzle")
const files = fs
  .readdirSync(dir)
  .filter((f) => f.endsWith(".sql"))
  .sort()
const entries = files.map((f) => ({ name: f.replace(/\.sql$/, ""), sql: fs.readFileSync(path.join(dir, f), "utf8") }))
const out = `// Generated by scripts/bundle-migrations.ts from drizzle/*.sql. Don't edit.
export const migrations: { name: string; sql: string }[] = ${JSON.stringify(entries, null, 2)}
`
fs.writeFileSync(path.join(root, "src/server/db/migrations.gen.ts"), out)
console.log(`bundled ${entries.length} migration(s)`)
